// The committed pgcat/ and pg/ packages must be exactly what the committed
// ledgers generate. If this fails:
//
//	go run ./cmd/pgcat gen -ledger pgcat.json -o pgcat
//	for f in ledgers/*.json; do go run ./cmd/pgcat gen -ledger $f -o pgcat; done
func TestGeneratedPackagesAreUpToDate(t *testing.T) {
	data, err := os.ReadFile("../../pgcat.json")
	if err != nil {
		t.Fatal(err)
	}
	l, err := pgcat.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	res, err := pgcat.Generate(l, "pg")
	if err != nil {
		t.Fatal(err)
	}
	want := map[string][]byte{}
	for n, src := range res.Files {
		want[n] = src
	}
	// The extension ledgers generate into pgcat/ext/<name>.
	exts, _ := filepath.Glob("../../ledgers/*.json")
	for _, f := range exts {
		switch filepath.Base(f) { // other ledgers share the directory
		case "commands.json", "grammar_map.json", "regress.json":
			continue
		}
		d, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		el, err := pgcat.Parse(d)
		if err != nil {
			t.Fatal(err)
		}
		r, err := pgcat.Generate(el, "pg")
		if err != nil {
			t.Fatal(err)
		}
		for n, src := range r.Files {
			want[n] = src
		}
	}
	for name, src := range want {
		got, err := os.ReadFile(filepath.Join("../../pgcat", name))
		if err != nil || !bytes.Equal(got, src) {
			t.Errorf("pgcat/%s is stale (err=%v)", name, err)
		}
	}
	// Nothing generated may linger after a wrapper disappears.
	filepath.WalkDir("../../pgcat", func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || strings.HasSuffix(path, "pgcat_test.go") { // hand-written
			return nil
		}
		rel, _ := filepath.Rel("../../pgcat", path)
		if _, ok := want[filepath.ToSlash(rel)]; !ok {
			t.Errorf("pgcat/%s is not generated by any ledger", rel)
		}
		return nil
	})
}

func TestGenerateIsDeterministic(t *testing.T) {
	data, _ := os.ReadFile("../../pgcat.json")
	l, _ := pgcat.Parse(data)
	a, _ := pgcat.Generate(l, "pg")
	b, _ := pgcat.Generate(l, "pg")
	for n, src := range a.Files {
		if !bytes.Equal(src, b.Files[n]) {
			t.Errorf("%s differs between runs", n)
		}
	}
}

// A ledger of one PostgreSQL major produces wrappers with no upper bound, and
// they fail the server tests of every later major. With QLX_RELEASE=1 (set
// by whoever cuts a release) a single-version ledger is an error; otherwise it
// is only reported.
func TestLedgerListsEveryTargetedMajor(t *testing.T) {
	data, err := os.ReadFile("../../pgcat.json")
	if err != nil {
		t.Fatal(err)
	}
	l, err := pgcat.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	if len(l.Versions) >= 4 {
		return
	}
	msg := "pgcat.json lists majors " + fmt.Sprint(l.Versions) + "; run scripts/release.sh with one server per major (16-19)"
	if os.Getenv("QLX_RELEASE") == "1" {
		t.Fatal(msg)
	}
	t.Log(msg)
}

// diff is a gate for scripts: exit status 0 only when the ledgers are the same.
func TestDiffExitStatus(t *testing.T) {
	dir := t.TempDir()
	write := func(name string, l *pgcat.Ledger) string {
		data, err := json.Marshal(l)
		if err != nil {
			t.Fatal(err)
		}
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, data, 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}
	fn := func(name string) pgcat.Fn {
		return pgcat.Fn{Name: name, Args: []string{"int4"}, Ret: "int4", Volatility: "i"}
	}
	a := write("a.json", &pgcat.Ledger{Versions: []int{18}, Funcs: []pgcat.Fn{fn("f")}})
	same := write("same.json", &pgcat.Ledger{Versions: []int{18}, Funcs: []pgcat.Fn{fn("f")}})
	other := write("other.json", &pgcat.Ledger{Versions: []int{18}, Funcs: []pgcat.Fn{fn("f"), fn("g")}})

	var out, errb bytes.Buffer
	if code := run([]string{"diff", a, same}, &out, &errb); code != 0 || out.String() != pgcat.NoDifferences {
		t.Errorf("identical ledgers: exit %d, output %q, stderr %q", code, out.String(), errb.String())
	}
	out.Reset()
	errb.Reset()
	if code := run([]string{"diff", a, other}, &out, &errb); code != 1 || !strings.Contains(out.String(), "Functions added") || !strings.Contains(errb.String(), "differ") {
		t.Errorf("different ledgers: exit %d, output %q, stderr %q", code, out.String(), errb.String())
	}
	out.Reset()
	errb.Reset()
	if code := run([]string{"diff", "-report", a, other}, &out, &errb); code != 0 || !strings.Contains(out.String(), "Functions added") {
		t.Errorf("-report must print and exit 0: exit %d, output %q", code, out.String())
	}
}

// Every extension ledger lists the majors of the catalog ledger. Like
// TestLedgerListsEveryTargetedMajor this only warns until QLX_RELEASE=1.
func TestExtensionLedgersListEveryMajor(t *testing.T) {
	data, err := os.ReadFile("../../pgcat.json")
	if err != nil {
		t.Fatal(err)
	}
	base, err := pgcat.Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	files, _ := filepath.Glob("../../ledgers/*.json")
	for _, f := range files {
		switch filepath.Base(f) {
		case "commands.json", "grammar_map.json", "regress.json":
			continue
		}
		data, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		l, err := pgcat.Parse(data)
		if err != nil {
			t.Fatalf("%s: %v", f, err)
		}
		if l.Extension == "" || slices.Equal(l.Versions, base.Versions) {
			continue
		}
		msg := fmt.Sprintf("%s lists majors %v, pgcat.json lists %v: extract it on every major and merge", filepath.Base(f), l.Versions, base.Versions)
		if os.Getenv("QLX_RELEASE") == "1" {
			t.Error(msg)
		} else {
			t.Log(msg)
		}
	}
}

func TestVersionsLike(t *testing.T) {
	dir := t.TempDir()
	write := func(name string, vs ...int) string {
		data, _ := json.Marshal(&pgcat.Ledger{Versions: vs})
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, data, 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}
	cat, full, one := write("cat.json", 16, 17, 18, 19), write("full.json", 16, 17, 18, 19), write("one.json", 16)
	var out, errb bytes.Buffer
	if code := run([]string{"versions", "-ledger", full, "-like", cat}, &out, &errb); code != 0 {
		t.Errorf("same majors: exit %d, %s", code, errb.String())
	}
	errb.Reset()
	if code := run([]string{"versions", "-ledger", one, "-like", cat}, &out, &errb); code != 1 || !strings.Contains(errb.String(), "[16]") {
		t.Errorf("one major: exit %d, %q", code, errb.String())
	}
}
