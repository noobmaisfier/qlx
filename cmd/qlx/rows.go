package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
)

// cmdRows writes ScanTargets methods for structs marked //qlx:row, so
// hand-written result types scan by position without reflection, exactly like
// generated rows and qlx.Tuple1..8:
//
//	//qlx:row
//	type UserSummary struct {
//		ID    int64
//		Email string
//		Posts int64 `qlx:"-"` // skipped: not a selected column
//	}
//
// Fields map to selected columns in declaration order. Embedded fields and
// generic types are rejected, because their column order would be a guess.
// Output goes to qlx_rows.go in each package directory.
func cmdRows(args []string, out io.Writer) error {
	fs := flag.NewFlagSet("rows", flag.ContinueOnError)
	root := fs.String("dir", ".", "directory containing the Go package")
	if err := fs.Parse(args); err != nil {
		return err
	}
	src, n, err := genRows(*root)
	if err != nil {
		return err
	}
	dst := filepath.Join(*root, "qlx_rows.go")
	if n == 0 {
		if _, err := os.Stat(dst); err == nil {
			if err := os.Remove(dst); err != nil {
				return err
			}
			fmt.Fprintf(out, "no //qlx:row structs left; removed %s\n", dst)
			return nil
		}
		fmt.Fprintln(out, "no //qlx:row structs found")
		return nil
	}
	if err := os.WriteFile(dst, src, 0o644); err != nil {
		return err
	}
	fmt.Fprintf(out, "wrote %s (%d row types)\n", dst, n)
	return nil
}

func genRows(dir string) ([]byte, int, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		n := fi.Name()
		return !strings.HasSuffix(n, "_test.go") && n != "qlx_rows.go"
	}, parser.ParseComments)
	if err != nil {
		return nil, 0, err
	}
	if len(pkgs) == 0 {
		return nil, 0, fmt.Errorf("no Go package in %s", dir)
	}
	var names []string
	for n := range pkgs {
		names = append(names, n)
	}
	sort.Strings(names)
	pkg := pkgs[names[0]]
	if len(names) > 1 {
		return nil, 0, fmt.Errorf("several packages in %s: %v", dir, names)
	}

	type row struct {
		name   string
		fields []string
	}
	var rows []row
	var files []string
	for fn := range pkg.Files {
		files = append(files, fn)
	}
	sort.Strings(files)
	for _, fn := range files {
		for _, d := range pkg.Files[fn].Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, sp := range gd.Specs {
				ts := sp.(*ast.TypeSpec)
				if !hasRowDirective(gd.Doc) && !hasRowDirective(ts.Doc) {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					return nil, 0, fmt.Errorf("%s: //qlx:row on %s, which is not a struct", fset.Position(ts.Pos()), ts.Name.Name)
				}
				if ts.TypeParams != nil {
					return nil, 0, fmt.Errorf("%s: //qlx:row does not support generic type %s", fset.Position(ts.Pos()), ts.Name.Name)
				}
				r := row{name: ts.Name.Name}
				for _, f := range st.Fields.List {
					if len(f.Names) == 0 {
						return nil, 0, fmt.Errorf("%s: %s has an embedded field; list its columns explicitly", fset.Position(f.Pos()), ts.Name.Name)
					}
					if f.Tag != nil {
						tag := reflect.StructTag(strings.Trim(f.Tag.Value, "`"))
						if tag.Get("qlx") == "-" {
							continue
						}
					}
					for _, id := range f.Names {
						r.fields = append(r.fields, id.Name)
					}
				}
				if len(r.fields) == 0 {
					return nil, 0, fmt.Errorf("%s: %s has no columns", fset.Position(ts.Pos()), ts.Name.Name)
				}
				rows = append(rows, r)
			}
		}
	}
	if len(rows) == 0 {
		return nil, 0, nil
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].name < rows[j].name })
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by qlx rows. DO NOT EDIT.\n\npackage %s\n\n", pkg.Name)
	for _, r := range rows {
		ptrs := make([]string, len(r.fields))
		for i, f := range r.fields {
			ptrs[i] = "&r." + f
		}
		fmt.Fprintf(&b, "// ScanTargets implements pgxexec.Scannable: one pointer per column, in field order.\nfunc (r *%s) ScanTargets() []any {\n\treturn []any{%s}\n}\n\n", r.name, strings.Join(ptrs, ", "))
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, 0, err
	}
	return src, len(rows), nil
}

func hasRowDirective(cg *ast.CommentGroup) bool {
	if cg == nil {
		return false
	}
	for _, c := range cg.List {
		if strings.TrimSpace(c.Text) == "//qlx:row" {
			return true
		}
	}
	return false
}
