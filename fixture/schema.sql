CREATE TABLE users (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      text NOT NULL UNIQUE,
    nickname   text,
    tier       text NOT NULL DEFAULT 'free',
    balance    bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE orders (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id),
    total   bigint NOT NULL,
    status  text NOT NULL
);
CREATE TABLE accounts (
    id      bigint PRIMARY KEY,
    balance bigint NOT NULL,
    owner   text
);

CREATE TYPE tier AS ENUM ('free', 'pro', 'enterprise');
CREATE DOMAIN positive_int AS integer CHECK (VALUE > 0);

CREATE TABLE members (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tier       tier NOT NULL DEFAULT 'free',
    seats      positive_int NOT NULL,
    tags       text[] NOT NULL DEFAULT '{}',
    settings   jsonb,
    active     boolean NOT NULL DEFAULT true,
    score      double precision,
    period     tstzrange,
    joined_at  timestamp NOT NULL DEFAULT now(),
    slug       text GENERATED ALWAYS AS (lower(id::text)) STORED,
    ref        bigint GENERATED ALWAYS AS IDENTITY
);

CREATE VIEW member_tiers AS SELECT id, tier FROM members;

CREATE FUNCTION add_seats(a integer, b integer) RETURNS integer
    LANGUAGE sql IMMUTABLE STRICT AS 'SELECT a + b';
CREATE PROCEDURE refresh_stats(n integer) LANGUAGE sql AS 'SELECT 1';
