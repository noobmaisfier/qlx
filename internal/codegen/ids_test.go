const idsSchema = `
CREATE TABLE authors (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   text NOT NULL,
    born   date,
    wakes  time,
    badge  timetz
);
CREATE TABLE posts (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id integer NOT NULL REFERENCES authors (id),
    parent_id bigint REFERENCES posts (id),
    views     bigint NOT NULL DEFAULT 0,
    posted_on date NOT NULL DEFAULT current_date
);
CREATE TABLE profiles (
    author_id integer PRIMARY KEY REFERENCES authors (id),
    bio       text
);
CREATE TABLE tags (
    a integer NOT NULL,
    b integer NOT NULL,
    PRIMARY KEY (a, b)
);
`

func idsGen(t *testing.T, cfg codegen.Config) *codegen.Result {
	t.Helper()
	srv, err := pgtool.StartEphemeral("")
	if err != nil {
		t.Skipf("no PostgreSQL server binaries: %v", err)
	}
	t.Cleanup(srv.Close)
	if err := srv.Conn().Exec(idsSchema); err != nil {
		t.Fatal(err)
	}
	raw, err := catalog.Load(srv.Conn(), []string{"public"})
	if err != nil {
		t.Fatal(err)
	}
	_, s, err := catalog.Seal(raw)
	if err != nil {
		t.Fatal(err)
	}
	cfg.Package, cfg.Schemas = "gen", []string{"public"}
	res, err := codegen.Generate(s, cfg)
	if err != nil {
		t.Fatal(err)
	}
	return res
}

func TestIDsAndDatesDefault(t *testing.T) {
	res := idsGen(t, codegen.Config{})
	a := string(res.Files["authors.go"])
	for _, want := range []string{"qt.Null[qt.Date]", "qt.Null[qt.TimeOfDay]", "qt.Null[qt.TimeTZ]", "qlx.TimeCol[qt.Null[qt.Date]]"} {
		if !strings.Contains(a, want) {
			t.Errorf("authors.go lacks %q", want)
		}
	}
	if strings.Contains(a, "IDSpace") {
		t.Error("ids default must keep plain integers")
	}
	if p := string(res.Files["posts.go"]); !strings.Contains(p, "qlx.NumCol[int64]") || strings.Contains(p, "qt.ID[") {
		t.Errorf("posts.go: integers must stay integers:\n%s", p)
	}
}

func TestIDsString(t *testing.T) {
	res := idsGen(t, codegen.Config{IDs: "string"})
	a := string(res.Files["authors.go"])
	for _, want := range []string{
		"type AuthorsIDSpace struct{}",
		`func (AuthorsIDSpace) IDSpace() string { return "public.authors" }`,
		"type AuthorID = qt.ID[AuthorsIDSpace]",
		"qlx.Col[qt.ID[AuthorsIDSpace]]",
	} {
		if !strings.Contains(a, want) {
			t.Errorf("authors.go lacks %q\n%s", want, a)
		}
	}
	p := string(res.Files["posts.go"])
	for _, want := range []string{
		"type PostsIDSpace struct{}",
		"qlx.Col[qt.ID[AuthorsIDSpace]]",        // FK to authors.id
		"qlx.Col[qt.Null[qt.ID[PostsIDSpace]]]", // self-referencing nullable FK
		"qlx.NumCol[int64]",                     // views stays an integer
		"ID       qt.ID[PostsIDSpace] ",         // the row field
	} {
		if !strings.Contains(p, want) {
			t.Errorf("posts.go lacks %q\n%s", want, p)
		}
	}
	// A primary key that is a foreign key shares the space of its target.
	pr := string(res.Files["profiles.go"])
	if strings.Contains(pr, "ProfilesIDSpace") || !strings.Contains(pr, "qt.ID[AuthorsIDSpace]") {
		t.Errorf("profiles.go must reuse the authors space:\n%s", pr)
	}
	// Composite keys are not ids.
	if tg := string(res.Files["tags.go"]); strings.Contains(tg, "IDSpace") {
		t.Errorf("composite key got an id type:\n%s", tg)
	}
}

func TestDateStdlib(t *testing.T) {
	res := idsGen(t, codegen.Config{Date: "stdlib"})
	a := string(res.Files["authors.go"])
	if strings.Contains(a, "qt.Date") || !strings.Contains(a, "qt.Null[time.Time]") {
		t.Errorf("date: stdlib must give time.Time:\n%s", a)
	}
}

func TestIDsGeneratedCodeBuilds(t *testing.T) {
	res := idsGen(t, codegen.Config{IDs: "string"})
	root, _ := filepath.Abs("../..")
	dir := t.TempDir()
	os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module gentest\n\ngo "+gover.Directive()+"\n\nrequire github.com/noobmaisfier/qlx v0.0.0\n\nreplace github.com/noobmaisfier/qlx => "+root+"\n"), 0o644)
	pkg := filepath.Join(dir, "gen")
	os.MkdirAll(pkg, 0o755)
	for n, src := range res.Files {
		os.WriteFile(filepath.Join(pkg, n), src, 0o644)
	}
	cmd := exec.Command("go", "vet", "./...")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOPROXY=off", "GOTOOLCHAIN=local")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("generated code does not build:\n%s", out)
	}
}
