			var cols []string
			for i := 0; i < 300; i++ {
				cols = append(cols, fmt.Sprintf("c%d int", i))
			}
			return fmt.Sprintf("CREATE TABLE %[1]s.empty ();\nCREATE TABLE %[1]s.wide (%s);", s, strings.Join(cols, ","))
