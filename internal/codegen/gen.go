// Package codegen turns a catalog.Schema into Go source: one typed symbol per
// table, enum, function and procedure. Output is deterministic (same lock,
// same bytes), which is what makes `qlx check` a byte comparison.
package codegen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"path"
	"sort"
	"strings"

	"github.com/noobmaisfier/qlx/internal/catalog"
)

// Config drives generation. It is the content of qlx.json.
type Config struct {
	Package   string    `json:"package"`
	Schemas   []string  `json:"schemas"`
	Out       string    `json:"out"`
	Exclude   []string  `json:"exclude,omitempty"` // "schema.table" or "table"
	Overrides Overrides `json:"overrides,omitempty"`
	// UUID chooses the Go type of uuid columns: "std" (default) is the
	// standard library's uuid.UUID (Go 1.27); "bytes" is [16]byte, for code
	// that must still build on an older toolchain.
	UUID string `json:"uuid,omitempty"`
	// JSONTypes sets the document type of a json or jsonb column: the key is
	// "table.column" (or "schema.table.column"), the value a Go type such as
	// "example.com/app/model.Settings". The column becomes qt.JSONB[Settings]
	// and reads and writes that type directly. Columns not listed stay
	// qt.JSONB[json.RawMessage].
	JSONTypes map[string]string `json:"json_types,omitempty"`
	// IDs chooses how integer keys appear in Go: "int" (default) keeps the
	// column's integer type; "string" types every single-column integer
	// primary key, and every foreign key that points at one, as the table's
	// qt.ID, whose text form is an opaque 11-character string (see qt.ID).
	// The database columns do not change.
	IDs string `json:"ids,omitempty"`
	// Date chooses the Go type of date columns: "qt" (default) is qt.Date, a
	// calendar date with no time zone; "stdlib" is time.Time at midnight UTC.
	Date string `json:"date,omitempty"`
	// Timestamptz chooses the Go type of timestamptz columns: "stdlib"
	// (default) is time.Time, which cannot hold 'infinity' (reading such a row
	// fails); "qt" is qt.Timestamptz, which can, and also reads and writes
	// -infinity.
	Timestamptz string `json:"timestamptz,omitempty"`
	// ArrayNulls types the elements of every array column as qt.Null[T], so a
	// NULL element can be read. PostgreSQL never says whether an array may hold
	// NULLs, so the default ([]T) fails, on the row that holds one, when it
	// does. Costs a wrapper per element.
	ArrayNulls bool `json:"array_nulls,omitempty"`
	// Targets lists the PostgreSQL majors the generated code must run on
	// (default 18 and 19). It is written into the generated package, where
	// the runtime and the analyzer read it: a construct newer than the oldest
	// target is rejected at build time.
	Targets []int `json:"targets,omitempty"`
	// Extensions names the extension packs to generate typed support for.
	Extensions []string `json:"extensions,omitempty"`
	// Nullable is the Go representation of nullable columns: "null" (the
	// default, qt.Null[T]). Pointer mode is not offered: a *T cannot tell
	// "NULL" from "not loaded", which is what Null[T] exists to prevent.
	Nullable string `json:"nullable,omitempty"`
}

// Result is the generated files plus anything the user should know about.
type Result struct {
	Files    map[string][]byte
	Warnings []string
	Skipped  []string // functions that have no typed wrapper, with the reason
}

type file struct {
	imports map[string]bool
	body    bytes.Buffer
}

func newFile() *file { return &file{imports: map[string]bool{}} }

func (f *file) p(format string, a ...any) { fmt.Fprintf(&f.body, format, a...) }
func (f *file) use(paths ...string) {
	for _, p := range paths {
		f.imports[p] = true
	}
}

// usesPackage reports whether the generated body refers to the package by
// its name (a selector such as qt.Null). When the body does not parse the
// answer is yes, so the real error comes from formatting.
func usesPackage(body []byte, name string) bool {
	fs := token.NewFileSet()
	af, err := parser.ParseFile(fs, "", append([]byte("package p\n"), body...), 0)
	if err != nil {
		return true
	}
	used := false
	ast.Inspect(af, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok && id.Name == name && id.Obj == nil {
				used = true
			}
		}
		return !used
	})
	return used
}

func (f *file) render(cfg Config, s *catalog.Schema) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString("// Code generated by qlx; DO NOT EDIT.\n")
	fmt.Fprintf(&out, "// Source: schema.lock %s (PostgreSQL %d)\n\n", s.Hash, s.Major())
	fmt.Fprintf(&out, "package %s\n\n", cfg.Package)
	f.use("github.com/noobmaisfier/qlx")
	for _, p := range []string{"github.com/noobmaisfier/qlx", "github.com/noobmaisfier/qlx/qt"} {
		if !usesPackage(f.body.Bytes(), path.Base(p)) {
			delete(f.imports, p) // a table with no settable column never touches qt
		}
	}
	var paths []string
	for p := range f.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	out.WriteString("import (\n")
	for _, p := range paths {
		fmt.Fprintf(&out, "\t%q\n", p)
	}
	out.WriteString(")\n\n")
	out.Write(f.body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("generated code for %s does not parse: %w", cfg.Package, err)
	}
	return src, nil
}

// Generate produces the Go package for a schema.
func Generate(s *catalog.Schema, cfg Config) (*Result, error) {
	if cfg.Package == "" {
		return nil, fmt.Errorf("config: package is required")
	}
	res := &Result{Files: map[string][]byte{}}
	m := newMapper(s, cfg, func(w string) { res.Warnings = append(res.Warnings, w) })
	nm := newNamer(cfg)
	exclude := m.exclude

	// Enums first: columns refer to their Go names.
	ef := newFile()
	ef.use("github.com/noobmaisfier/qlx")
	var enums []catalog.Type
	for _, t := range s.Types {
		if t.Kind == "e" {
			enums = append(enums, t)
		}
	}
	for _, t := range enums {
		m.enumNames[t.OID] = nm.take(nm.local(t.Schema, t.Name), camel(t.Schema))
	}
	for _, t := range enums {
		emitEnum(ef, nm, m.enumNames[t.OID], t, s)
	}
	if len(enums) > 0 {
		src, err := ef.render(cfg, s)
		if err != nil {
			return res, err
		}
		res.Files["enums.go"] = src
	}

	multiSchema := len(cfg.Schemas) > 1
	var gens []*tableGen
	byKey := map[string]*tableGen{}
	for _, t := range s.Tables {
		if exclude[t.Schema+"."+t.Name] || exclude[t.Name] {
			continue
		}
		g := newTableGen(m, nm, t, multiSchema, cfg.JSONTypes)
		g.all = byKey
		byKey[t.Schema+"."+t.Name] = g
		gens = append(gens, g)
	}
	if nm.err != nil {
		return res, nm.err
	}
	for _, g := range gens {
		t := g.t
		f := newFile()
		g.emit(f)
		src, err := f.render(cfg, s)
		if err != nil {
			return res, err
		}
		fn := strings.ToLower(t.Name)
		if multiSchema {
			fn = strings.ToLower(t.Schema) + "_" + fn
		}
		res.Files[uniqueFile(sanitizeFile(fn), res.Files)+".go"] = src
	}

	ff := newFile()
	emitFuncs(ff, m, nm, s, res)
	if ff.body.Len() > 0 {
		src, err := ff.render(cfg, s)
		if err != nil {
			return res, err
		}
		res.Files["functions.go"] = src
	}

	rf := newFile()
	emitSpec(rf, s, cfg)
	src, err := rf.render(cfg, s)
	if err != nil {
		return res, err
	}
	res.Files["register.go"] = src
	sort.Strings(res.Warnings)
	sort.Strings(res.Skipped)
	return res, nil
}

// uniqueFile makes a table's file name usable and unique: Go ignores files
// that start with "_" or ".", and two tables whose names differ only in
// characters sanitizeFile replaces ("a b", "a-b") would otherwise overwrite
// each other's file and silently lose a table.
func uniqueFile(base string, taken map[string][]byte) string {
	if base == "" || base[0] == '_' {
		base = "t" + base
	}
	name := base
	for i := 2; ; i++ {
		if _, dup := taken[name+".go"]; !dup && name != "enums" && name != "functions" && name != "register" {
			return name
		}
		name = base + "_" + itoa(i)
	}
}

func sanitizeFile(s string) string {
	b := []byte(s)
	for i, c := range b {
		if !(c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '_') {
			b[i] = '_'
		}
	}
	out := string(b)
	// _test and platform suffixes would change how Go treats the file.
	for _, suf := range []string{"_test", "_linux", "_windows", "_darwin", "_amd64", "_arm64"} {
		if strings.HasSuffix(out, suf) {
			out += "_t"
			break
		}
	}
	return out
}

func emitEnum(f *file, nm *namer, goName string, t catalog.Type, s *catalog.Schema) {
	en, _ := s.EnumByOID(t.OID)
	f.p("// %s is the PostgreSQL enum %s.%s.\ntype %s string\n\n", goName, t.Schema, t.Name, goName)
	f.p("const (\n")
	seen := map[string]bool{}
	var names []string
	for _, l := range en.Labels {
		c := goName + camel(l)
		for i := 2; seen[c] || nm.used[c] && !seen[c]; i++ {
			c = goName + camel(l) + itoa(i)
		}
		seen[c] = true
		nm.used[c] = true
		names = append(names, c)
		f.p("\t%s %s = %q\n", c, goName, l)
	}
	f.p(")\n\n")
	f.p("// %sValues lists every label in sort order.\nvar %sValues = []%s{%s}\n\n", goName, goName, goName, strings.Join(names, ", "))
	if len(names) == 0 { // PostgreSQL allows ENUM (): no label is valid, and "case :" would not parse
		f.p("// Valid reports whether v is a label of the enum.\nfunc (%s) Valid() bool { return false }\n\n", goName)
	} else {
		f.p("// Valid reports whether v is a label of the enum.\nfunc (v %s) Valid() bool {\n\tswitch v {\n\tcase %s:\n\t\treturn true\n\t}\n\treturn false\n}\n\n", goName, strings.Join(names, ", "))
	}
	f.p("// %sType is the type symbol, for casts.\nvar %sType = qlx.NewPgType[%s](%q, %q)\n\n", goName, goName, goName, t.Schema, t.Name)
}

func emitSpec(f *file, s *catalog.Schema, cfg Config) {
	f.p("// ABI ties this package to the runtime it was generated for: a runtime\n// without this constant does not compile against this code.\nconst _ = qlx.ABI1\n\n")
	f.p("// Spec describes the database this package was generated from.\nvar Spec = qlx.SchemaSpec{\n")
	f.p("\tSchemas: []string{")
	for i, sc := range cfg.Schemas {
		if i > 0 {
			f.p(", ")
		}
		f.p("%q", sc)
	}
	f.p("},\n\tTargets: []int{")
	targets := cfg.Targets
	if len(targets) == 0 {
		targets = []int{18, 19}
	}
	for i, t := range targets {
		if i > 0 {
			f.p(", ")
		}
		f.p("%d", t)
	}
	f.p("},\n\tHash: %q,\n\tFingerprints: map[string]string{\n", s.Hash)
	for _, t := range s.Tables {
		f.p("\t\t%q: %q,\n", t.Schema+"."+t.Name, t.Fingerprint)
	}
	f.p("\t},\n\tFingerprintSQL: %q,\n}\n", catalog.FingerprintSQL)
}
