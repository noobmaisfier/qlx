package pgcat

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// Docs renders the generated reference pages for the pgcat packages: an index
// with coverage numbers, one page of functions per first letter and one page
// of operators. Every row says which PostgreSQL versions have the entry, so
// the version gates are documented from the same ledger that produces them.
// The output is deterministic, so it can be checked in and diffed in review.
func Docs(l *Ledger, res *Result, pkg string) map[string][]byte {
	files := map[string][]byte{}
	versions := "unknown"
	if len(l.Versions) > 0 {
		var vs []string
		for _, v := range l.Versions {
			vs = append(vs, fmt.Sprint(v))
		}
		versions = strings.Join(vs, ", ")
	}

	byLetter := map[string][]WrapperInfo{}
	var ops []WrapperInfo
	for _, w := range res.Wrappers {
		if w.IsOp {
			ops = append(ops, w)
			continue
		}
		k := strings.ToLower(w.Go[:1])
		if k < "a" || k > "z" {
			k = "x"
		}
		byLetter[k] = append(byLetter[k], w)
	}
	var letters []string
	for k := range byLetter {
		letters = append(letters, k)
	}
	sort.Strings(letters)

	var idx bytes.Buffer
	fmt.Fprintf(&idx, "# Built-in function reference\n\nGenerated by `pgcat docs` from the ledger of PostgreSQL %s. Do not edit. Wrappers live in `pgcat/<area>`; the most-used are also re-exported by package `%s`.\n\n", versions, pkg)
	fmt.Fprintf(&idx, "- Functions: %d in the catalog, %d wrapped\n- Operators: %d in the catalog, %d wrapped\n\n", res.Report.Funcs, res.Report.FuncsWrapped, res.Report.Ops, res.Report.OpsWrapped)
	fmt.Fprint(&idx, "## Pages\n\n")
	for _, k := range letters {
		fmt.Fprintf(&idx, "- [Functions %s](functions-%s.md) (%d)\n", strings.ToUpper(k), k, len(byLetter[k]))
	}
	fmt.Fprintf(&idx, "- [Operators](operators.md) (%d)\n\n", len(ops))
	if len(res.Report.Skipped) > 0 {
		fmt.Fprintln(&idx, "## Not wrapped\n\n| Reason | Entries |\n|---|---|")
		var rs []string
		for r := range res.Report.Skipped {
			rs = append(rs, r)
		}
		sort.Strings(rs)
		for _, r := range rs {
			fmt.Fprintf(&idx, "| %s | %d |\n", r, res.Report.Skipped[r])
		}
	}
	files["README.md"] = idx.Bytes()

	page := func(title string, ws []WrapperInfo) []byte {
		var b bytes.Buffer
		fmt.Fprintf(&b, "# %s\n\n| Go | PostgreSQL | Returns | Versions | Notes |\n|---|---|---|---|---|\n", title)
		for _, w := range ws {
			notes := []string{}
			if w.Volatile != "" {
				notes = append(notes, w.Volatile)
			}
			if w.Nullable {
				notes = append(notes, "may return NULL")
			}
			fmt.Fprintf(&b, "| `%s.%s` | `%s` | `%s` | %s | %s |\n", w.Area, w.Go, esc(w.Sig), w.Ret, versionRange(w.Since, w.Until), strings.Join(notes, ", "))
		}
		return b.Bytes()
	}
	for _, k := range letters {
		files["functions-"+k+".md"] = page("Functions "+strings.ToUpper(k), byLetter[k])
	}
	files["operators.md"] = page("Operators", ops)
	return files
}

func esc(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// versionRange words a Since/Until pair: "all", "17+", "up to 16" or "17-18".
func versionRange(since, until int) string {
	switch {
	case since == 0 && until == 0:
		return "all"
	case until == 0:
		return fmt.Sprintf("%d+", since)
	case since == 0:
		return fmt.Sprintf("up to %d", until-1)
	}
	return fmt.Sprintf("%d–%d", since, until-1)
}
